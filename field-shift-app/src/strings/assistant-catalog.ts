type Prefixed<T> = { [K in keyof T as K extends `unit.${string}` ? never : `assistant.${K & string}`]: T[K] }

/**
 * The English copy `en.ts` spreads into the app catalog, keys prefixed with `assistant.`. Unit
 * symbols stay out: block 6 R-11 keeps unit symbols out of the catalog as data values.
 * There is no Portuguese copy for `pt-BR.ts`: block 3 R-37 (kept by block 6 R-11 and block 8
 * R-43) leaves that file empty, so the Portuguese assistant strings are read from `assistantPtBR`
 * here. Moving them into `pt-BR.ts` is a team decision (see FIELD_SHIFT_AI_MVP.md).
 */
export const assistantCatalogEn = Object.fromEntries(
  Object.entries(assistantEn)
    .filter(([key]) => !key.startsWith('unit.'))
    .map(([key, value]) => [`assistant.${key}`, value]),
) as Prefixed<typeof assistantEn>
